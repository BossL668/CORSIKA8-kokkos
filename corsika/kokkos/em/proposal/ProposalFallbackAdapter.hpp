namespace corsika::kokkos {

  /**
   * A draw-id range reserved for final states generated by CPU PROPOSAL after
   * the GPU has already selected type, component and v.
   *
   * GPU-native final-state kernels currently use small process-local draw
   * identifiers. Keeping CPU PROPOSAL draws above 2^32 prevents accidental
   * stream aliasing while retaining the same scheduling-independent Philox
   * addressing scheme.
   */
  inline constexpr std::uint64_t CpuProposalFinalStateDrawIdBase = std::uint64_t{1} << 32;

  inline bool is_known_proposal_interaction_type(std::int32_t processId) noexcept;

  /**
   * These fallback reasons are emitted after the GPU has selected the exact
   * PROPOSAL process and target component, but before it has obtained v from
   * the bounded inverse-CDF table. The CPU may therefore complete v without
   * resampling the already selected interaction.
   */
  inline bool proposal_fallback_requires_selected_loss(
      FallbackRequest const& event) noexcept;

  /**
   * Validate the common interaction identity and vertex state independently
   * of whether the fractional loss has already been resolved.
   */
  inline bool has_specified_proposal_interaction_identity(
      FallbackRequest const& event) noexcept;

  /**
   * True when only v is missing and the original GPU loss quantile is
   * available for exact CPU completion.
   */
  inline bool has_resolvable_proposal_selected_loss(
      FallbackRequest const& event) noexcept;

  /**
   * True only when a fallback contains everything needed to call
   * SecondariesCalculator::CalculateSecondaries() without selecting the
   * interaction again.
   */
  inline bool has_specified_proposal_final_state(FallbackRequest const& event) noexcept;

  /**
   * Authorize only the deliberately specified CPU final-state fallbacks.
   *
   * Data completeness alone is not authorization: InvalidFinalState and
   * transport/table failures can also retain a syntactically complete
   * interaction record.  Retrying those through PROPOSAL would hide a device
   * defect.  CPU-only processes are active callers. Historical Epair exhaustion reason
   * identifiers are retained without enabling a device rejection sampler.
   */
  inline bool permits_specified_proposal_cpu_final_state(
      FallbackRequest const& event) noexcept;

  namespace proposal_fallback_detail {
    inline proposal::ProposalInteractionRecord make_record_from_identity(
        FallbackRequest const& event, std::uint64_t randomSeed, std::uint64_t showerId);
  } // namespace proposal_fallback_detail

  /**
   * Convert the device fallback record to the existing CPU-side specified
   * interaction record. Position is converted m -> cm and energy GeV -> MeV.
   */
  inline proposal::ProposalInteractionRecord make_proposal_interaction_record(
      FallbackRequest const& event, std::uint64_t randomSeed, std::uint64_t showerId);

  /**
   * Convert an interaction whose process/component are specified but whose
   * fractional loss must still be completed by CPU PROPOSAL.
   */
  inline proposal::ProposalInteractionRecord
  make_proposal_interaction_record_for_selected_loss(FallbackRequest const& event,
                                                     std::uint64_t randomSeed,
                                                     std::uint64_t showerId);

  inline std::vector<double> make_proposal_final_state_random_numbers(
      FallbackRequest const& event, std::size_t count, std::uint64_t randomSeed,
      std::uint64_t showerId);

  /**
   * Complete a device-selected fallback with an InteractionModel-compatible
   * CPU generator. The model validates the medium and interaction hashes,
   * then calls only the specified final-state calculator.
   */
  template <typename TProposalInteractionModel>
  auto generate_specified_proposal_final_state(TProposalInteractionModel& model,
                                               FallbackRequest const& event,
                                               std::uint64_t randomSeed,
                                               std::uint64_t showerId);

} // namespace corsika::kokkos
