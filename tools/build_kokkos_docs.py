#!/usr/bin/env python3
"""Build the standalone developer guide and check its internal links."""

import argparse
from html.parser import HTMLParser
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
from urllib.parse import unquote, urlsplit
import xml.etree.ElementTree as ET


def build_api(root, output):
    """Extract public declarations without compiling physics dependencies."""
    executable = shutil.which(os.environ.get("DOXYGEN", "doxygen"))
    if executable is None:
        raise RuntimeError("Doxygen is required; see documentation/kokkos/BUILDING.rst")
    directory = output.parent / "api-doxygen"
    directory.mkdir(parents=True, exist_ok=True)
    headers = sorted((root / "corsika/kokkos").rglob("*.hpp"))
    if not headers:
        raise RuntimeError("No Kokkos public headers found; check the source checkout")
    if (root / ".git").exists() and shutil.which("git"):
        tracked = subprocess.check_output(
            ["git", "ls-files", "--", "corsika/kokkos"], cwd=root, text=True).splitlines()
        missing = [name for name in tracked if name.endswith(".hpp")
                   and not (root / name).is_file()]
        if missing:
            raise RuntimeError("Incomplete public-header checkout: " + ", ".join(missing))
    # Doxygen does not remove XML files for headers removed since a previous run.
    # This directory is generated by this builder, never used as a source input.
    if (directory / "xml").is_dir():
        shutil.rmtree(directory / "xml")
    configuration = (root / "documentation/kokkos/Doxyfile").read_text()
    for key, value in (("INPUT", root / "corsika/kokkos"),
                       ("OUTPUT_DIRECTORY", directory),
                       ("STRIP_FROM_PATH", root), ("STRIP_FROM_INC_PATH", root)):
        quoted = str(value).replace("\\", "\\\\").replace('"', '\\"')
        configuration += f'\n{key} = "{quoted}"\n'
    config = directory / "Doxyfile"
    config.write_text(configuration, encoding="utf-8")
    subprocess.run([executable, str(config)], cwd=root, check=True)
    if not (directory / "xml/index.xml").is_file():
        raise RuntimeError("Doxygen completed without producing xml/index.xml")
    index = ET.parse(directory / "xml/index.xml").getroot()
    extracted = set()
    for item in index.findall("compound[@kind='file']"):
        compound = ET.parse(directory / "xml" / (item.attrib["refid"] + ".xml"))
        location = compound.find("compounddef/location")
        if location is not None:
            extracted.add(location.attrib["file"])
    expected = {str(path.relative_to(root)) for path in headers}
    if extracted != expected:
        raise RuntimeError(f"Doxygen header coverage mismatch: missing={expected-extracted}, "
                           f"unexpected={extracted-expected}")
    manifest = {
        "doxygen": subprocess.check_output([executable, "--version"], text=True).strip(),
        "headers": {str(path.relative_to(root)): hashlib.sha256(path.read_bytes()).hexdigest()
                    for path in headers},
        "configuration_sha256": hashlib.sha256(
            (root / "documentation/kokkos/Doxyfile").read_bytes()).hexdigest(),
    }
    (directory / "inputs.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return directory / "xml"


class PageLinks(HTMLParser):
    """Collect local links, asset references and HTML anchors."""

    def __init__(self):
        super().__init__()
        self.anchors = set()
        self.links = []

    def handle_starttag(self, tag, attributes):
        attributes = dict(attributes)
        if attributes.get("id"):
            self.anchors.add(attributes["id"])
        if tag == "a" and attributes.get("name"):
            self.anchors.add(attributes["name"])
        for key in ("href", "src"):
            if attributes.get(key):
                self.links.append(attributes[key])


def check_site(output):
    pages = {}
    for path in sorted(output.rglob("*.html")):
        parser = PageLinks()
        parser.feed(path.read_text(encoding="utf-8"))
        pages[path.resolve()] = parser

    errors = []
    checked = 0
    for path, page in pages.items():
        for link in page.links:
            parts = urlsplit(link)
            if parts.scheme or parts.netloc:
                continue
            if parts.path.startswith("/"):
                target = output / unquote(parts.path.lstrip("/"))
            else:
                target = path.parent / unquote(parts.path) if parts.path else path
            if target.is_dir():
                target = target / "index.html"
            target = target.resolve()
            checked += 1
            if not target.is_file():
                errors.append(f"{path.relative_to(output)}: missing target {link}")
            elif parts.fragment and target in pages:
                if unquote(parts.fragment) not in pages[target].anchors:
                    errors.append(f"{path.relative_to(output)}: missing anchor {link}")

    report = {"html_pages": len(pages), "internal_references": checked,
              "errors": errors, "output": str(output)}
    (output.parent / "site-check.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8"
    )
    if errors:
        raise RuntimeError("Internal link check failed:\n" + "\n".join(errors))
    print(f"Checked {len(pages)} HTML pages and {checked} internal references.")


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        default=root / "build/kokkos-docs/html")
    args = parser.parse_args()
    output = args.output.resolve()
    source = root / "documentation/kokkos"
    api_xml = build_api(root, output)
    environment = dict(os.environ, C8_DOCS_DOXYGEN_XML=str(api_xml))
    subprocess.run(
        [sys.executable, "-m", "sphinx", "-b", "html", "-E", "-a", "-n", "-W",
         "--keep-going", "-j", "1", str(source), str(output)], check=True,
        env=environment,
    )
    shutil.copyfile(api_xml.parent / "inputs.json", output / "api-inputs.json")
    (output / ".nojekyll").touch()
    check_site(output)
    print(f"Preview: {output / 'index.html'}")


if __name__ == "__main__":
    main()
