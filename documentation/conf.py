    doc_url = 'https://corsika-8.readthedocs.io/en/'+build_version
    configureDoxyfile("Doxyfile.in", "Doxyfile", "../", "_build/workdir/doxygen")
    configureDoxyLayout("DoxyLayout.in", "DoxyLayout.xml", doc_url , "CORSIKA 8 Webpage")
